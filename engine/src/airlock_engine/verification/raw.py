"""Search the stored bytes of a protected copy for protected values.

Re-extraction checks what a reader would see; this checks what is *stored*:
every part of an Office package is decompressed (embedded Office files too)
and searched as text, so a value left in an XML part no extractor reads
(an orphaned string, a cache, a custom property) is still caught.

Runs in the isolated worker: it reads the copy and receives the protected
values over the worker's private pipe, like the sanitize plan.
"""

from __future__ import annotations

import html
import io
import re
import zipfile
from collections.abc import Iterator, Sequence

from airlock_engine.masking.sweep import Sweeper

#: Limits for the copy's own package (it was written by Airlock, but a
#: verifier must never be the weak point).
MAX_PART_BYTES = 512 * 1024 * 1024
MAX_TOTAL_BYTES = 2 * 1024 * 1024 * 1024
MAX_DEPTH = 3
_SAFE_NAME = frozenset("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_./-[]")


#: Font family names ("Microsoft Himalaya") are typography, not document
#: content: they are blanked before searching, so a protected word that is
#: also part of a font name does not fail the check.
_FONT_ATTRS = re.compile(r'\b(?:typeface|w:ascii|w:hAnsi|w:eastAsia|w:cs)="[^"]*"')
_FONT_TABLE_ATTRS = re.compile(r'\b(?:w:name|w:altName)="[^"]*"')


def _without_fonts(name: str, text: str) -> str:
    if not name.endswith((".xml", ".rels")):
        return text
    text = _FONT_ATTRS.sub("", text)
    if name.endswith("fontTable.xml"):
        text = _FONT_TABLE_ATTRS.sub("", text)
    return text


def part_label(name: str) -> str:
    """A part name is generated by Office ("word/document.xml"); anything
    unusual is not shown at all."""
    return name if name and len(name) <= 120 and set(name) <= _SAFE_NAME else "a part of the file"


def _decode(data: bytes) -> str:
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return data.decode("utf-16", "ignore")
    return data.decode("utf-8", "ignore")


def _texts(data: bytes, name: str, depth: int, budget: list[int]) -> Iterator[tuple[str, str]]:
    if depth < MAX_DEPTH and data[:4] == b"PK\x03\x04":
        try:
            package = zipfile.ZipFile(io.BytesIO(data))
        except zipfile.BadZipFile:
            package = None
        if package is not None:
            with package:
                for info in package.infolist():
                    if info.is_dir() or info.file_size > MAX_PART_BYTES:
                        continue
                    budget[0] -= info.file_size
                    if budget[0] < 0:
                        raise ValueError("package too large to verify")
                    inner = package.read(info)
                    label = info.filename if depth == 0 else f"{name}/{info.filename}"
                    yield from _texts(inner, label, depth + 1, budget)
            return
    text = _without_fonts(name, _decode(data))
    yield name, text
    if "&" in text:
        yield name, html.unescape(text)


def outside(
    sweeper: Sweeper, text: str, replacements: Sweeper | None
) -> list[tuple[int, int, str]]:
    """Matches that are not part of text Airlock inserted itself (a fake name
    such as "Sam Example" may contain a short protected word)."""
    matches = sweeper.find(text)
    if not matches or replacements is None or not replacements:
        return matches
    spans = [(s, e) for s, e, _ in replacements.find(text)]
    return [m for m in matches if not any(s <= m[0] and m[1] <= e for s, e in spans)]


def raw_hits(
    data: bytes, values: Sequence[str], replacements: Sequence[str] = ()
) -> list[tuple[int, str]]:
    """(index of the value, part label) for every protected value found."""
    sweeper = Sweeper((v, str(i)) for i, v in enumerate(values) if v)
    if not sweeper:
        return []
    inserted = Sweeper((r, r) for r in replacements if len(r) >= 2)
    found: set[tuple[int, str]] = set()
    for name, text in _texts(data, "file", 0, [MAX_TOTAL_BYTES]):
        for _, _, index in outside(sweeper, text, inserted):
            found.add((int(index), part_label(name)))
    return sorted(found)
