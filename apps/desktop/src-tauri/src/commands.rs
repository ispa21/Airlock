//! Tauri commands exposed to the web view.
//!
//! The web view can only reach the engine through `engine_call`, and only for
//! the methods in `ALLOWED_METHODS`. Lifecycle methods such as
//! `system.shutdown` are reserved for the host.

use std::path::PathBuf;
use std::sync::Arc;
use std::time::Duration;

use serde_json::{json, Value};
use tauri::{AppHandle, Manager, State};
use tauri_plugin_dialog::DialogExt;

use crate::engine::{Engine, EngineError, EngineInfo};

const ALLOWED_METHODS: &[&str] = &[
    "system.health",
    "document.inspect",
    "document.extract",
    "scan.start",
    "scan.set_profile",
    "scan.override",
    "scan.refresh",
    "scan.teach",
    "scan.discard",
    "verify.run",
    "export.text",
    "allowlist.status",
    "allowlist.clear",
    "profiles.list",
    "profiles.create",
    "profiles.update",
    "profiles.delete",
    "profiles.set_default",
    "sanitize.run",
    "sanitize.discard",
    "vault.restore",
    "vault.forget",
    "vault.status",
    "rules.list",
    "rules.create",
    "rules.update",
    "rules.delete",
    "rules.add_category",
];

fn timeout_for(method: &str) -> Duration {
    match method {
        "document.inspect" => Duration::from_secs(30),
        // The engine enforces its own 15-minute extraction limit; this only
        // guards against a wedged engine.
        "document.extract" => Duration::from_secs(1_000),
        // Extraction (≤ 15 min, enforced by the engine) plus detection.
        "scan.start" => Duration::from_secs(1_500),
        // The sanitize worker has the same 15-minute limit as extraction.
        "sanitize.run" => Duration::from_secs(1_000),
        // Detection again on the text already read (no extraction).
        "scan.refresh" | "scan.teach" => Duration::from_secs(600),
        // Reading the copy back is an extraction (≤ 15 min) plus detection.
        "verify.run" => Duration::from_secs(1_500),
        "export.text" => Duration::from_secs(60),
        _ => Duration::from_secs(10),
    }
}

/// UI request tags are short opaque tokens.
fn valid_tag(tag: &str) -> bool {
    (1..=64).contains(&tag.len())
        && tag
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

async fn blocking<T: Send + 'static>(
    job: impl FnOnce() -> Result<T, EngineError> + Send + 'static,
) -> Result<T, EngineError> {
    tauri::async_runtime::spawn_blocking(job)
        .await
        .map_err(|_| EngineError::engine_unavailable())?
}

/// Starts the engine if necessary and returns its handshake details.
#[tauri::command]
pub async fn engine_status(engine: State<'_, Arc<Engine>>) -> Result<EngineInfo, EngineError> {
    let engine = engine.inner().clone();
    blocking(move || engine.info()).await
}

#[tauri::command]
pub async fn engine_call(
    engine: State<'_, Arc<Engine>>,
    method: String,
    params: Option<Value>,
    tag: Option<String>,
) -> Result<Value, EngineError> {
    if !ALLOWED_METHODS.contains(&method.as_str()) {
        return Err(EngineError::method_not_allowed());
    }
    let params = params.unwrap_or_else(|| json!({}));
    if !params.is_object() || tag.as_deref().is_some_and(|t| !valid_tag(t)) {
        return Err(EngineError::invalid_params());
    }
    let engine = engine.inner().clone();
    let timeout = timeout_for(&method);
    blocking(move || engine.call_tagged(&method, params, timeout, tag.as_deref())).await
}

/// Protected-copy ids are generated by the engine: `art_` + 16 hex digits.
fn valid_artifact_id(id: &str) -> bool {
    id.len() == 20 && id.starts_with("art_") && id[4..].bytes().all(|b| b.is_ascii_hexdigit())
}

/// The save dialog may return a name without the extension on some platforms;
/// add it only when that cannot silently replace an existing file.
fn with_extension(path: PathBuf, extension: &str) -> PathBuf {
    if path.extension().is_some() {
        return path;
    }
    let candidate = path.with_extension(extension);
    if candidate.exists() {
        path
    } else {
        candidate
    }
}

/// Save a verified protected copy, or its text, where the user chooses.
///
/// The destination comes from the native save dialog shown here, never from
/// the web view: `export.prepare` and `export.save` are not in
/// `ALLOWED_METHODS`. The engine checks the copy and the path again.
#[tauri::command]
pub async fn export_save(
    app: AppHandle,
    engine: State<'_, Arc<Engine>>,
    artifact_id: String,
    as_text: bool,
    acknowledge_review: bool,
) -> Result<Value, EngineError> {
    if !valid_artifact_id(&artifact_id) {
        return Err(EngineError::invalid_params());
    }
    let engine = engine.inner().clone();
    blocking(move || {
        let mut params = json!({
            "artifact_id": artifact_id,
            "as_text": as_text,
            "acknowledge_review": acknowledge_review,
        });
        let prepared = engine.call_tagged(
            "export.prepare",
            params.clone(),
            Duration::from_secs(30),
            None,
        )?;
        let text = |key: &str| prepared[key].as_str().unwrap_or_default().to_owned();
        let (file_name, extension, label) =
            (text("file_name"), text("extension"), text("filter_label"));
        let mut dialog = app
            .dialog()
            .file()
            .set_title(if as_text {
                "Save the protected text"
            } else {
                "Save the protected copy"
            })
            .set_file_name(file_name)
            .add_filter(label, &[extension.as_str()]);
        if let Some(window) = app.get_webview_window("main") {
            dialog = dialog.set_parent(&window);
        }
        let Some(chosen) = dialog.blocking_save_file() else {
            return Ok(json!({ "saved": false }));
        };
        let path = chosen
            .into_path()
            .map_err(|_| EngineError::invalid_params())?;
        let path = with_extension(path, &extension);
        let destination = path.to_str().ok_or_else(EngineError::invalid_params)?;
        params["destination"] = json!(destination);
        let mut saved =
            engine.call_tagged("export.save", params, Duration::from_secs(300), None)?;
        saved["saved"] = json!(true);
        Ok(saved)
    })
    .await
}

/// Cancel the in-flight request started with `tag`. Returns whether one was found.
#[tauri::command]
pub async fn engine_cancel(
    engine: State<'_, Arc<Engine>>,
    tag: String,
) -> Result<bool, EngineError> {
    if !valid_tag(&tag) {
        return Err(EngineError::invalid_params());
    }
    let engine = engine.inner().clone();
    blocking(move || Ok(engine.cancel(&tag))).await
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lifecycle_methods_are_not_exposed() {
        assert!(!ALLOWED_METHODS.contains(&"system.shutdown"));
        assert!(!ALLOWED_METHODS.contains(&"system.hello"));
        assert!(ALLOWED_METHODS.iter().all(|m| !m.starts_with("$/")));
    }

    #[test]
    fn scan_methods_are_exposed_with_a_long_timeout() {
        assert!(ALLOWED_METHODS.contains(&"scan.start"));
        assert!(ALLOWED_METHODS.contains(&"rules.create"));
        assert!(ALLOWED_METHODS.contains(&"scan.override"));
        assert!(ALLOWED_METHODS.contains(&"profiles.list"));
        assert!(ALLOWED_METHODS.contains(&"sanitize.run"));
        assert!(ALLOWED_METHODS.contains(&"scan.teach"));
        assert!(ALLOWED_METHODS.contains(&"allowlist.clear"));
        assert!(timeout_for("scan.refresh") > timeout_for("system.health"));
        assert!(ALLOWED_METHODS.contains(&"verify.run"));
        assert!(timeout_for("verify.run") >= timeout_for("scan.start"));
    }

    #[test]
    fn destinations_never_come_from_the_web_view() {
        assert!(ALLOWED_METHODS.contains(&"export.text"));
        assert!(!ALLOWED_METHODS.contains(&"export.save"));
        assert!(!ALLOWED_METHODS.contains(&"export.prepare"));
    }

    #[test]
    fn artifact_ids_are_checked() {
        assert!(valid_artifact_id("art_0123456789abcdef"));
        assert!(!valid_artifact_id("art_0123456789abcdeg"));
        assert!(!valid_artifact_id("art_../../etc/passwd"));
        assert!(!valid_artifact_id(""));
    }

    #[test]
    fn a_missing_extension_is_added_only_when_safe() {
        let dir = std::env::temp_dir().join(format!("airlock-ext-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        assert_eq!(
            with_extension(dir.join("copy"), "docx"),
            dir.join("copy.docx")
        );
        assert_eq!(
            with_extension(dir.join("copy.txt"), "docx"),
            dir.join("copy.txt")
        );
        std::fs::write(dir.join("taken.docx"), b"x").unwrap();
        assert_eq!(with_extension(dir.join("taken"), "docx"), dir.join("taken"));
        std::fs::remove_dir_all(&dir).unwrap();
        assert!(timeout_for("sanitize.run") > timeout_for("system.health"));
        assert!(timeout_for("scan.start") > timeout_for("document.extract"));
    }

    #[test]
    fn tags_are_short_opaque_tokens() {
        assert!(valid_tag("scan-1a2b_3"));
        assert!(!valid_tag(""));
        assert!(!valid_tag("../etc"));
        assert!(!valid_tag(&"x".repeat(65)));
    }
}
